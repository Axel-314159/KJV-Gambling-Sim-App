import { Pool } from 'pg';
import crypto from 'crypto';

// Adjust to match your local/staging DB credentials
const pool = new Pool({
  connectionString:
    process.env.DATABASE_URL || 'postgres://kjv_game_dev_user:cascodeTest2026@127.0.0.1:5432/kjv_game_dev',
});

const randInt = (min: number, max: number) => Math.floor(Math.random() * (max - min + 1)) + min;

async function seed() {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    console.log('Seeding database with fake users and bet history...');

    // 1. Create 10 Active Users
    const userIds: string[] = [];
    
    // We use a dummy hash for "password123". If your app uses bcrypt/argon2, 
    // you won't be able to log in as these users unless you replace this with your hash function.
    const dummyPasswordHash = crypto.createHash('sha256').update('password123').digest('hex');

    for (let i = 1; i <= 10; i++) {
      const username = `player_${i}`;
      const email = `player${i}@example.com`;

      const { rows } = await client.query(
        `INSERT INTO users (username, email, password_hash, role, status, wallet_balance, initial_grant, auto_register)
         VALUES ($1, $2, $3, 'PLAYER', 'ACTIVE', 20000, 20000, true)
         RETURNING id`,
        [username, email, dummyPasswordHash]
      );
      const userId = rows[0].id;
      userIds.push(userId);

      // Give them their initial 1,000 Shekels (20,000 Gerahs)
      await client.query(
        `INSERT INTO wallet_ledger (user_id, entry_type, amount, balance_after)
         VALUES ($1, 'INITIAL_GRANT', 20000, 20000)`,
        [userId]
      );
    }
    console.log('✅ Created 10 users with 1,000 Shekel initial balances.');

    // 2. Create 5 Completed Rounds (Past 5 days)
    for (let r = 5; r >= 1; r--) {
      const date = new Date();
      date.setDate(date.getDate() - r);
      const dateStr = date.toISOString().split('T')[0];

      const { rows: roundRows } = await client.query(
        `INSERT INTO rounds (
           round_date, status, registration_opens_at, betting_opens_at, betting_closes_at,
           registered_count, max_verses_per_player, total_pot, min_stake_per_verse
         ) VALUES (
           $1, 'COMPLETED', $2, $3, $4, 10, 500, 0, 20
         ) RETURNING id`,
        [
          dateStr,
          new Date(date.setHours(8, 0, 0, 0)),
          new Date(date.setHours(12, 0, 0, 0)),
          new Date(date.setHours(20, 0, 0, 0)),
        ]
      );
      const roundId = roundRows[0].id;
      let roundPot = 0;

      // 3. Register users and create fake bets
      for (const userId of userIds) {
        // Register the user (submission_count = 2 simulates a locked-in final slip)
        await client.query(
          `INSERT INTO round_registrations (round_id, user_id, submission_count)
           VALUES ($1, $2, 2)`,
          [roundId, userId]
        );

        // Fetch current balance to maintain accurate ledger progression
        const { rows: balRows } = await client.query(
          `SELECT wallet_balance FROM users WHERE id = $1`,
          [userId]
        );
        let currentBalance = Number(balRows[0].wallet_balance);

        // Each user makes 1 to 3 segment bets
        const numSegments = randInt(1, 3);
        
        for (let s = 0; s < numSegments; s++) {
          // Space out verses to avoid the GIST exclude self-overlap constraint
          const startVerse = randInt(1 + s * 10000, 9000 + s * 10000);
          const length = randInt(3, 100);
          const endVerse = startVerse + length - 1;
          
          // Bet 1-5 shekels per verse
          const stakeShekels = randInt(1, 5) * length;
          const stakeGerahs = stakeShekels * 20;

          if (currentBalance < stakeGerahs) break;

          // Deduct Stake
          currentBalance -= stakeGerahs;
          roundPot += stakeGerahs;

          // Simulate an outcome (30% Won, 40% Collided, 30% Refunded)
          const roll = Math.random();
          const outcome = roll > 0.7 ? 'WON' : roll > 0.3 ? 'COLLIDED' : 'REFUNDED';
          
          let payoutGerahs = 0;
          if (outcome === 'WON') {
            payoutGerahs = stakeGerahs * randInt(2, 5); // 2x-5x return
          } else if (outcome === 'REFUNDED') {
            payoutGerahs = stakeGerahs; // Return original stake
          }

          // Insert Bet (verse_length and verse_range are auto-generated by the DB)
          const { rows: betRows } = await client.query(
            `INSERT INTO bets (round_id, user_id, start_verse_id, end_verse_id, stake, outcome, payout)
             VALUES ($1, $2, $3, $4, $5, $6, $7)
             RETURNING id`,
            [roundId, userId, startVerse, endVerse, stakeGerahs, outcome, payoutGerahs]
          );
          const betId = betRows[0].id;

          // Record Stake Deduction Ledger Entry
          await client.query(
            `INSERT INTO wallet_ledger (user_id, round_id, bet_id, entry_type, amount, balance_after)
             VALUES ($1, $2, $3, 'SLIP_STAKE', $4, $5)`,
            [userId, roundId, betId, -stakeGerahs, currentBalance]
          );

          // Record Payout Ledger Entry
          if (payoutGerahs > 0) {
            currentBalance += payoutGerahs;
            const entryType = outcome === 'WON' ? 'ROUND_WINNING' : 'ROUND_NO_WINNER_REFUND';
            await client.query(
              `INSERT INTO wallet_ledger (user_id, round_id, bet_id, entry_type, amount, balance_after)
               VALUES ($1, $2, $3, $4, $5, $6)`,
              [userId, roundId, betId, entryType, payoutGerahs, currentBalance]
            );
          }
        }

        // Save final post-round balance to the user
        await client.query(
          `UPDATE users SET wallet_balance = $1 WHERE id = $2`,
          [currentBalance, userId]
        );
      }

      // Update the round's total pot size
      await client.query(`UPDATE rounds SET total_pot = $1 WHERE id = $2`, [roundPot, roundId]);
      console.log(`✅ Seeded Round #${roundId} (${dateStr}) | Pot: ${Math.floor(roundPot / 20)} Shekels`);
    }

    await client.query('COMMIT');
    console.log('🎉 Successfully seeded fake users and history!');
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('❌ Error seeding database. Rolled back changes:', err);
  } finally {
    client.release();
    await pool.end();
  }
}

seed();